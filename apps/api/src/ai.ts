// Dynamic import for ESM package
let GoogleGenAI: any = null;

const SYSTEM_PROMPT = `
You are an expert integration architect generating FlowForge workflows.
FlowForge executes graphs of nodes. The incoming event payload is referenced by
its top-level fields directly (e.g. account_tier, amount, customer.email) — there
is NO "webhook.body" wrapper. Interpolate values into strings with {{path}},
e.g. {{customer.email}} or {{order.id}}.

Available node types:
1. "trigger" - Config: { triggerType: "webhook", subtitle: "POST /v1/events/webhook" }
2. "logic" - Config: { condition: string } where condition is a SIMPLE comparison the
   engine evaluates safely (no arbitrary JS). Supported forms:
     - "field === 'value'" , "field !== 'value'"
     - "field > 100" , "field < 100" , "field >= 100" , "field <= 100"
     - "customer.email.endsWith('.io')" , "field.includes('text')" , "field.startsWith('x')"
   Connect a logic node's outgoing edges with sourceHandle "true" or "false" to branch.
3. "action" HTTP Request - Config: { actionType: "http", method: "GET"|"POST"|"PUT"|"DELETE"|"PATCH", url: string, headers?: string (JSON), body?: string (JSON) }
4. "action" Email - Config: { actionType: "email", toAddress: string, subject: string, emailBody: string }
5. "action" Save to database - Config: { actionType: "sink", tableName: string, dataMapping: string (JSON mapping columns to values, using {{path}}) }. The target table must already exist.
6. "action" AI Transform - Config: { actionType: "ai", systemPrompt: string, userInput: string }

Always include a "label" in each node's config describing it.

You must output ONLY valid JSON matching this schema:
{
  "version": 3,
  "nodes": [
    { "id": "unique_string", "type": "trigger"|"logic"|"action", "config": {}, "position": { "x": number, "y": number } }
  ],
  "edges": [
    { "source": "node_id", "target": "node_id", "sourceHandle": "true"|"false" (only for logic branches) }
  ]
}

Layout nodes left to right (e.g. x: 100, x: 400, x: 700) with y: 300.
Do not wrap JSON in markdown tags like \`\`\`json. Just output the raw JSON.
`;

export async function generateWorkflow(prompt: string) {
  if (!process.env.GEMINI_API_KEY) {
    console.warn("GEMINI_API_KEY not set, falling back to mock generation");
    return generateMockWorkflow(prompt);
  }

  try {
    if (!GoogleGenAI) {
      const pkg = await import('@google/genai');
      GoogleGenAI = pkg.GoogleGenAI;
    }
    
    const ai = new GoogleGenAI({ apiKey: process.env.GEMINI_API_KEY });
    
    const response = await ai.models.generateContent({
      model: 'gemini-2.5-flash',
      contents: [
        { role: 'user', parts: [{ text: SYSTEM_PROMPT + "\\n\\nUser Request: " + prompt }] }
      ],
      config: {
        temperature: 0.1,
        responseMimeType: 'application/json'
      }
    });

    const text = response.text || '';
    const parsed = JSON.parse(text.trim());
    return parsed;
  } catch (error) {
    console.error("AI Generation failed, falling back to mock", error);
    return generateMockWorkflow(prompt);
  }
}

function generateMockWorkflow(prompt: string) {
  const isInstagram = prompt.toLowerCase().includes('instagram');
  const isCondition = prompt.toLowerCase().includes('if') || prompt.toLowerCase().includes('filter') || prompt.toLowerCase().includes('only');
  
  const nodes: any[] = [
    { id: "trigger_1", type: "trigger", config: { label: "Webhook Intake", triggerType: "webhook", subtitle: "POST /v1/events/webhook" }, position: { x: 200, y: 300 } }
  ];
  const edges: any[] = [];
  let lastNode = "trigger_1";
  let lastHandle: string | null = null;
  let x = 500;

  if (isCondition) {
    const cid = "condition_1";
    nodes.push({
      id: cid,
      type: "logic",
      config: { label: "Condition Branch", condition: "account_tier === 'enterprise'", subtitle: "IF: account_tier === 'enterprise'" },
      position: { x, y: 300 }
    });
    edges.push({ source: lastNode, target: cid });
    lastNode = cid;
    lastHandle = "true"; // downstream action runs on the TRUE branch
    x += 300;
  }

  const actionId = "action_1";
  if (isInstagram) {
    nodes.push({
      id: actionId,
      type: "action",
      config: { actionType: "http", label: "Publish Image", method: "POST", url: "https://httpbin.org/post", body: '{"imageUrl":"{{order.id}}","caption":"Generated by FlowForge AI"}' },
      position: { x, y: 300 }
    });
  } else {
    nodes.push({
      id: actionId,
      type: "action",
      config: { actionType: "http", label: "HTTP Request", method: "POST", url: "https://httpbin.org/post", body: '{"event":"{{event}}","customer":"{{customer.email}}"}' },
      position: { x, y: 300 }
    });
  }
  edges.push(lastHandle ? { source: lastNode, target: actionId, sourceHandle: lastHandle } : { source: lastNode, target: actionId });

  return { version: 3, nodes, edges };
}
